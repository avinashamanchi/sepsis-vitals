#!/usr/bin/env python3
"""Generate the secrets file for a single-server site installation.

    python scripts/setup_site.py [--env-file docker/.env] [--app-url http://ward-server:8000]

Writes every secret the Docker Compose stack needs, generated on this
machine with the operating system's random source:

- database and Redis passwords;
- the RSA key pair for sign-in tokens;
- the patient-identifier encryption key;
- the configuration, webhook and reset-token keys.

The file is created with owner-only permissions (0600). No secret is
printed.

It refuses to overwrite an existing file. Replacing SEPSIS_PII_KEY would
make every stored patient identifier unreadable, and replacing the
database password would lock the API out of the existing database. To
rotate keys, follow docs/pii_key_rotation.md instead.

Keep a copy of the file somewhere safe and offline (for example an
encrypted USB drive in a locked cabinet). Without it, encrypted data and
backups cannot be read.
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _rsa_pair() -> tuple:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import rsa

    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    private = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.TraditionalOpenSSL,
                                serialization.NoEncryption()).decode()
    public = key.public_key().public_bytes(serialization.Encoding.PEM,
                                           serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    return private, public


def _one_line(pem: str) -> str:
    """PEM as one line with literal \\n, the form the compose stack reads."""
    return pem.strip().replace("\n", "\\n")


def build_env(app_url: str) -> str:
    private, public = _rsa_pair()
    values = {
        "SEPSIS_ENV": "production",
        "POSTGRES_PASSWORD": secrets.token_hex(24),
        "REDIS_PASSWORD": secrets.token_hex(24),
        "GRAFANA_PASSWORD": secrets.token_hex(16),
        "SEPSIS_PII_KEY": base64.b64encode(os.urandom(32)).decode(),
        "SEPSIS_CONFIG_KEY": base64.urlsafe_b64encode(os.urandom(32)).decode(),
        "SEPSIS_WEBHOOK_SECRET": secrets.token_hex(32),
        "SEPSIS_TOKEN_SECRET": secrets.token_hex(32),
        "JWT_PRIVATE_KEY": _one_line(private),
        "JWT_PUBLIC_KEY": _one_line(public),
        "SEPSIS_APP_URL": app_url,
    }
    header = (
        "# Generated by scripts/setup_site.py. Secrets: do not commit, email or print this file.\n"
        "# Keep an offline copy: without SEPSIS_PII_KEY, encrypted data and backups cannot be read.\n"
    )
    return header + "".join(f"{k}={v}\n" for k, v in values.items())


def write_env(path: Path, app_url: str) -> None:
    if path.exists():
        raise FileExistsError(
            f"{path} already exists. It holds the keys for existing data and is never "
            "overwritten. To rotate keys, see docs/pii_key_rotation.md."
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(build_env(app_url))


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--env-file", default=str(ROOT / "docker" / ".env"))
    parser.add_argument("--app-url", default="http://localhost:8000",
                        help="address staff use to open the dashboard (used in password-reset links)")
    opts = parser.parse_args(argv)
    path = Path(opts.env_file)
    try:
        write_env(path, opts.app_url)
    except FileExistsError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    print(f"Wrote {path} (permissions 0600). Next: docs/low_resource_deployment.md, step 3.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
