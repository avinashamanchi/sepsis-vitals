#!/usr/bin/env python3
"""Evaluate the committed model artifact on a fresh synthetic cohort.

    python scripts/evaluate_committed_model.py

Writes reports/committed_model_evaluation.{json,md}. Engineering evidence
only: the cohort comes from the synthetic generator, not from patients.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import warnings
from pathlib import Path

from sepsis_vitals.ml.model_evaluation import evaluate_committed_model
from sepsis_vitals.ml.provenance import markdown as provenance_markdown
from sepsis_vitals.ml.provenance import run_provenance

ROOT = Path(__file__).resolve().parents[1]


def _ci(arm: dict) -> str:
    ci = arm.get("ci")
    return f"{arm['estimate']:.3f} ({ci[0]:.3f}–{ci[1]:.3f})" if ci else f"{arm['estimate']:.3f}"


def _pct(v) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}%"


def _md(r: dict) -> str:
    c, d, cal = r["cohort"], r["discrimination"], r["calibration"]
    model, age = d["arms"]["model"], d["arms"]["age_only"]
    diff = d["differences_vs_reference"]["age_only"]["auroc"]
    lines = [
        "# Committed model: evaluation on a fresh synthetic cohort",
        "",
        "**Engineering evidence only.** The cohort is generated by the same hand-written",
        "generator family the model was trained on. Nothing here estimates performance in",
        "patients, supports a clinical claim, or validates a threshold.",
        "",
        "## Evidence by source",
        "",
        "| Source | Status |",
        "| --- | --- |",
        "| Synthetic (this report) | Done. See the sections below. |",
        "| Retrospective, real de-identified data | **None.** No data-use approval. The MIMIC-IV demo files"
        " that some local tests can read were not used. |",
        "| Prospective (silent mode) | **None.** It needs a protocol, ethics approval, a site and data access"
        " (docs/pilot/clinical_requirements.md). |",
        "",
        "## Model and data",
        "",
        f"- Artifact: {r['model']['model_name']} {r['model']['model_version']}, sha256 "
        f"`{r['model']['artifact_sha256'][:16]}…`, feature schema `{r['model']['feature_schema_sha256'][:16]}…`, "
        f"validation status `{r['model']['validation_status']}`.",
        f"- Cohort: {r['cohort_generator']['generator']}, {r['cohort_generator']['n_patients']:,} patients, "
        f"prevalence {r['cohort_generator']['sepsis_prevalence']}, seed {r['cohort_generator']['seed']} "
        f"(training used seed {r['cohort_generator']['training_seed']}). {r['cohort_generator']['note']}",
        f"- Dataset sha256 `{r['dataset']['sha256']}`.",
        f"- Label: {r['label']}",
        "- Leakage: the model never saw this cohort, which was generated after training with a different"
        " seed. All rows of a patient stay together in the bootstrap.",
        "",
        "## Cohort",
        "",
        f"- {c['patients']:,} patients ({c['septic_patients']:,} septic), {c['observations']:,} observations,"
        f" {c['patient_days']:,} patient-days; median {c['observations_per_patient_median']:g} observations"
        f" per patient.",
        f"- Positive observations: {c['positive_rows']:,} ({_pct(c['row_positive_rate'])}). Median age"
        f" {c['age_median']:g}. Sex: {c['sex']}.",
        "- Missing fraction per observation: "
        + ", ".join(f"{k} {_pct(v)}" for k, v in c["missing_fraction"].items()) + ".",
        "",
        "## Discrimination (observation level; 95% patient-cluster bootstrap,"
        f" {d['n_boot']:,} replicates)",
        "",
        "| Score | AUROC | AUPRC |",
        "| --- | ---: | ---: |",
        f"| Model | {_ci(model['auroc'])} | {_ci(model['auprc'])} |",
        f"| Age alone (no model) | {_ci(age['auroc'])} | {_ci(age['auprc'])} |",
        "",
        f"Age alone minus model, AUROC: {diff['estimate']:+.3f}"
        + (f" ({diff['ci'][0]:+.3f} to {diff['ci'][1]:+.3f})" if diff.get("ci") else "") + ".",
        "",
        "## Calibration",
        "",
        f"- Mean output {cal['mean_output']:.3f} against an observed rate of {cal['observed_rate']:.3f}."
        f" Slope {cal['slope']:.2f}, intercept {cal['intercept']:.2f}.",
        "",
        "| Output decile mean | Observed rate | Observations |",
        "| ---: | ---: | ---: |",
        *[f"| {b['mean_output']:.3f} | {b['observed_rate']:.3f} | {b['n_rows']:,} |"
          for b in cal["reliability_by_decile"]],
        "",
        "## Decision curve (observation level, illustrative thresholds)",
        "",
        "| Threshold | Net benefit: model | Net benefit: act on all |",
        "| ---: | ---: | ---: |",
        *[f"| {x['threshold']:.2f} | {x['net_benefit_model']:.4f} | {x['net_benefit_all']:.4f} |"
          for x in r["decision_curve"]],
        "",
        "The thresholds are only points on a curve; none of them is a proposed operating point.",
        "",
        "## Alert burden and false-alarm trade-off",
        "",
        f"Threshold policy `{r['threshold_policy']['id']}` ({r['threshold_policy']['status']}).",
        "",
        "| Rule | Sens. | Spec. | PPV | Septic pts flagged at/after onset | Septic pts flagged before onset"
        " | Non-septic pts ever flagged | Flagged obs. per patient-day |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
        *[f"| {b['rule']} | {_pct(b['sensitivity'])} | {_pct(b['specificity'])} | {_pct(b['ppv'])} | "
          f"{_pct(b['septic_patients_flagged_at_or_after_onset'])} | {_pct(b['septic_patients_flagged_before_onset'])} | "
          f"{_pct(b['non_septic_patients_ever_flagged'])} | {b['flagged_observations_per_patient_day']} |"
          for b in r["alert_burden"]],
        "",
        f"Of {r['alert_sources']['alerts']:,} observations that the deployed rule flags,"
        f" {r['alert_sources']['rules_only']:,} come from the rule-based scores alone and"
        f" {r['alert_sources']['model_only']:,} from the model alone.",
        "",
        "Sensitivity and specificity are per observation against the current-state label. Flags"
        " before onset count as false positives there, although they are what an early warning would"
        " aim for, so both views are shown.",
        "",
        "## Subgroups",
        "",
        "| Subgroup | Observations | Positive | AUROC | Mean output | Observed rate |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
        *[f"| {name} | {g['rows']:,} | {g['positive_rows']:,} | {g['auroc'] if g['auroc'] is not None else 'n/a'} |"
          f" {g['mean_output']} | {g['observed_rate']} |" for name, g in r["subgroups"].items()],
        "",
        "## Behaviour checks (does an abnormal finding raise the output?)",
        "",
        f"Gate: {r['behaviour_gate']['rule']}. **Result: {'PASSED' if r['behaviour_gate']['passed'] else 'FAILED'}.**"
        " The cut-offs are the SIRS and qSOFA criteria already in `scores.py`. This is an engineering"
        " plausibility check, not clinical validation.",
        "",
        "| Finding | Observations | Share where it lowered the output | Mean change | Median change | Gate |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
        *[f"| {name} | {p['rows']:,} | {_pct(p['share_where_value_lowered_output'])} | "
          f"{p['mean_change_in_output']:+.4f} | {p['median_change_in_output']:+.4f} | "
          f"{'pass' if r['behaviour_gate']['results'][name] else 'FAIL'} |" for name, p in r["failure_probes"].items()],
        "",
        "## Known limitations",
        "",
        "- Every number comes from the synthetic generator, which encodes assumptions written by hand."
        " The cohort profile is shown above.",
        "- Discrimination from vital signs alone is modest. That is expected for vital-sign screening; the"
        " published UVA score reached AUC 0.77 for in-hospital mortality on real data (Moore 2017).",
        "- Temperature is not constrained (fever and hypothermia both matter), so its effect is learned"
        " from the generator only.",
        "- Unregistered patients are scored as first observations at the API, which uses less"
        " information than the trend-based training rows (see Subgroups).",
        "- Rule-based scores produce most alerts. The model can add an alert but never remove one.",
        "- History: the previous committed model (GradientBoosting 2.0.0, legacy generator, with labs)"
        " failed every behaviour check, because its training data made septic vital signs look *less*"
        " abnormal (finding N53). It is archived; see PROJECT_REVIEW.md.",
        "",
        "## What this means",
        "",
        "This model behaves plausibly on synthetic data and is suitable for exercising the software, for"
        " demonstrations, and for the silent-mode data-collection workflow. **It is not suitable for clinical"
        " decisions.** That requires retraining and validation on approved local data, with the clinical"
        " decisions listed in docs/pilot/clinical_requirements.md.",
        "",
        *provenance_markdown(r["provenance"]),
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--patients", type=int, default=4000)
    parser.add_argument("--seed", type=int, default=20261015)
    parser.add_argument("--bootstrap", type=int, default=1000)
    parser.add_argument("--generator-profile", default="physiologic",
                        help="synthetic cohort profile (sepsis_vitals.ml.profile_evaluation.PROFILES)")
    parser.add_argument("--model-dir", default=str(ROOT / "models"))
    parser.add_argument("--output-dir", default=str(ROOT / "reports"))
    opts = parser.parse_args()
    warnings.filterwarnings("ignore")
    started = time.monotonic()

    report = evaluate_committed_model(opts.model_dir, n_patients=opts.patients, seed=opts.seed,
                                      n_boot=opts.bootstrap, generator_profile=opts.generator_profile)
    report["provenance"] = run_provenance(
        seeds={"cohort": opts.seed, "bootstrap": opts.seed % 100000},
        dataset={"description": f"synthetic generator ({opts.generator_profile} profile), {opts.patients:,} patients;",
                 **report["dataset"]},
        candidates="not applicable: evaluates the committed artifact",
        runtime_seconds=time.monotonic() - started,
        command="python scripts/evaluate_committed_model.py " + " ".join(sys.argv[1:]),
    )
    out = Path(opts.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "committed_model_evaluation.json").write_text(json.dumps(report, indent=2, default=str) + "\n")
    md = _md(report)
    (out / "committed_model_evaluation.md").write_text(md + "\n")
    print(md)


if __name__ == "__main__":
    main()
